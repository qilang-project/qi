//! 源码位置换算工具：字节偏移 → 行列。
//!
//! AST 节点的 `Span`（见 `crate::lexer::tokens::Span`）保存的是**原始源码的
//! UTF-8 字节偏移**（parser 预处理按等字节数替换实现，偏移不漂移；lexer 的
//! token span 亦按 `len_utf8` 递增）。诊断输出「文件:行:列」时用本模块换算。

/// 把 UTF-8 字节偏移换算为 (1-based 行, 1-based 列)。
///
/// - 列按**字符**计数（非字节），中文等多字节字符占 1 列，报错读起来自然。
/// - `偏移` 落在多字节字符中间时，归到该字符本身（不会 panic、不切坏 UTF-8）。
/// - `偏移` 超过源码长度时，返回末尾位置（最后一行的行尾再 +1 列）。
pub fn 偏移转行列(源码: &str, 偏移: usize) -> (usize, usize) {
    let mut 行 = 1usize;
    let mut 列 = 1usize;
    for (字节位, 字符) in 源码.char_indices() {
        // 目标偏移落在当前字符的字节范围内（含首字节）：定位到该字符
        if 偏移 <= 字节位 {
            break;
        }
        if 偏移 < 字节位 + 字符.len_utf8() {
            // 偏移指进了多字节字符中间 → 归到该字符
            break;
        }
        if 字符 == '\n' {
            行 += 1;
            列 = 1;
        } else {
            列 += 1;
        }
    }
    (行, 列)
}

#[cfg(test)]
mod tests {
    use super::偏移转行列;

    #[test]
    fn 空源码_偏移零() {
        assert_eq!(偏移转行列("", 0), (1, 1));
    }

    #[test]
    fn 首行首列() {
        assert_eq!(偏移转行列("变量 x = 1;\n", 0), (1, 1));
    }

    #[test]
    fn 中文多字节_同行列按字符数() {
        // "变量 x" —— 变(3B) 量(3B) 空格(1B) x(1B)
        // 偏移 6 = 空格 → 第 1 行第 3 列；偏移 7 = x → 第 1 行第 4 列
        let src = "变量 x = 1;";
        assert_eq!(偏移转行列(src, 6), (1, 3));
        assert_eq!(偏移转行列(src, 7), (1, 4));
    }

    #[test]
    fn 偏移落在多字节字符中间_归到该字符() {
        // 偏移 1、2 都在「变」(0..3) 内部 → 与偏移 0 同位置
        let src = "变量";
        assert_eq!(偏移转行列(src, 0), (1, 1));
        assert_eq!(偏移转行列(src, 1), (1, 1));
        assert_eq!(偏移转行列(src, 2), (1, 1));
        assert_eq!(偏移转行列(src, 3), (1, 2));
    }

    #[test]
    fn 跨行_行首() {
        // 第 1 行 "包 主程序;"（3+1+9+1 = 14 字节）+ '\n'（1 字节）
        let src = "包 主程序;\n变量 x = 1;\n";
        let 第二行首 = "包 主程序;\n".len(); // 15
        assert_eq!(偏移转行列(src, 第二行首), (2, 1));
    }

    #[test]
    fn 行尾换行符本身() {
        // 偏移指向 '\n'：位于该行行尾（最后字符的下一列）
        let src = "ab\ncd";
        assert_eq!(偏移转行列(src, 2), (1, 3)); // '\n' 在第 1 行第 3 列
        assert_eq!(偏移转行列(src, 3), (2, 1)); // 'c'
        assert_eq!(偏移转行列(src, 4), (2, 2)); // 'd'
    }

    #[test]
    fn 偏移超出末尾_收敛到文件尾() {
        let src = "ab\ncd";
        assert_eq!(偏移转行列(src, 5), (2, 3));
        assert_eq!(偏移转行列(src, 999), (2, 3));
    }

    #[test]
    fn 第三行中文声明_典型诊断场景() {
        let src = "包 主程序;\n函数 入口() {\n    变量 x: 整数 = \"你好\";\n}\n";
        // 第 3 行的「变量」起点 = 前两行字节数 + 4 个空格缩进
        let 第三行首 = src.lines().take(2).map(|l| l.len() + 1).sum::<usize>();
        let 变量偏移 = 第三行首 + 4;
        assert_eq!(偏移转行列(src, 变量偏移), (3, 5));
    }
}
