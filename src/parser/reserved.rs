//! 保留字表 —— **唯一事实源在 `grammar.lalrpop` 的终结符**，这里是它的副本。
//!
//! 两者由 `tests/关键字表一致性.rs` 双向强制相等。以前只强制单向（
//! keywords.rs ⊆ 语法），于是「语法有、表里没有」的十来个词长期让报错提示失真。
//!
//! ## 为什么需要这张表
//!
//! LALRPOP 内建词法器里**字面量优先于标识符正则**：一个词只要在语法里当过
//! 终结符，它就永远走不到 `Identifier` 的正则分支，用户写 `变量 结果: 整数`
//! 只会收到「意外的标记 `结果`」。反过来，**不再是终结符的词会立刻落到正则
//! 分支上** —— 所以 `Identifier` 里那两条手写的拒绝链必须跟着这张表走，
//! 否则刚放开的词会被链子重新拒掉。这就是把它收成一处的直接原因。
//!
//! 往语法里加终结符前先想清楚：每个保留字都从用户手里偷走一个名字。

/// 语法里全部中文终结符。
