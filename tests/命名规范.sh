#!/usr/bin/env bash
# 命名规范门禁 —— 两类反复犯的错，靠记是记不住的，所以放进 make ci。
#
# ① 中文标识符只许出现在 .qi 里。离开 qi 就换英文：JS/TS 变量、HTML class/id、
#    shell 变量、线上协议键。面向用户的**文本**和注释照样中文，那是给人看的。
#    重灾区是 qi 里反引号内嵌的 <script>：上下文全中文，手一顺 JS 局部变量也
#    写成中文了。shell 更狠 —— bash 不支持非 ASCII 变量名，`中文=1` 会被当命令
#    执行，失败后变量为空、断言静默通过。
#
# ② `$变量` 紧跟全角标点。bash（5.3 也一样）把标点第一个字节吃进变量名，
#    set -u 下报「var?: 未绑定的变量」并打死脚本。这写法几乎只在**出错路径**上，
#    平时不执行，能潜伏很久 —— wasm 断言脚本的四个 FAIL 分支就是这样。写 ${var}。
#
# ── 这个脚本自己连栽两次，都是「假绿」，值得记 ──
#   第一版：用了个"聪明"的参数转发函数，五条规则一条没生效，报通过。
#   第二版：`xargs -0 grep -P` —— 管道里拿到的是**系统 BSD grep**（没有 -P），
#           直接敲 grep 拿到的却是支持 -P 的包装。它报错了，但被 2>/dev/null
#           吞掉 → 空结果 → 报通过。
#   **别把干活那一步的 stderr 丢掉**，那等于把失败变成通过。
#   现在整个扫描交给 python3，不依赖任何 grep 方言。
set -uo pipefail
exec python3 "$(dirname "$0")/命名规范.py" "$(cd "$(dirname "$0")/../.." && pwd)"
